import { createRequire } from 'node:module';
import { mkdir,readFile,writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const root=resolve(import.meta.dirname,'..');
await mkdir(resolve(root,'test-output'),{recursive:true});
const {password}=JSON.parse(await readFile(resolve(root,'runtime/settings.json'),'utf8'));
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required']});
const logs=[],errors=[];
const context=await browser.newContext({viewport:{width:1440,height:960}});
const page=await context.newPage();
page.on('console',m=>logs.push(m.text()));
page.on('pageerror',e=>{errors.push(e.message);console.log('PAGE ERROR '+e.message);});
page.on('requestfailed',r=>console.log('FAILED '+r.url()+' '+r.failure()?.errorText));
await page.goto('http://localhost:8088/');
await page.screenshot({path:resolve(root,'test-output/lobby.png'),fullPage:true});
await page.locator('#nickname').fill('TestRanger');
await page.locator('#password').fill(password);
await page.locator('#join-button').click();
await page.locator('#agree').waitFor({state:'visible',timeout:25000});
console.log('EULA displayed');
await page.locator('#agree').click();
console.log('EULA accepted for test session; loading assets.');
await page.locator('#viewport').waitFor({state:'visible',timeout:45000});
await page.waitForTimeout(12000);
await page.screenshot({path:resolve(root,'test-output/game.png')});
await writeFile(resolve(root,'test-output/browser-log.txt'),logs.join('\n'));
console.log('Recent client output:\n'+logs.slice(-35).join('\n'));
console.log('UI: '+(await page.locator('#viewport-frame').innerText()).slice(-1500));
console.log('Browser errors: '+JSON.stringify(errors));
await browser.close();
